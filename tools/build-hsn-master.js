// Builds js/hsn-master.js from the official GST HSN/SAC list (data/HSN_SAC.xlsx).
// Source: https://tutorial.gst.gov.in/downloads/HSN_SAC.xlsx — re-download and re-run to update.
// Run: npm run hsn
const fs = require('fs');
const path = require('path');
const XLSX = require('xlsx');
const P = require('../js/parsers.js');

const src = path.join(__dirname, '..', 'data', 'HSN_SAC.xlsx');
const codes = P.parseHsnMaster(XLSX, XLSX.readFile(src));
const updated = fs.statSync(src).mtime.toISOString().slice(0, 10);
const body = '/* Official GST HSN/SAC master (' + Object.keys(codes).length + ' codes), generated by tools/build-hsn-master.js from HSN_SAC.xlsx on ' + updated + '. */\n' +
  'window.GST_HSN_MASTER = ' + JSON.stringify({ updated, codes }) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'hsn-master.js'), body);
console.log('Wrote js/hsn-master.js with', Object.keys(codes).length, 'codes');
